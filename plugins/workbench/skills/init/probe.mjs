// A file the walk found but the process cannot open is a fact for the brief —
// every caller falls back to '' and would otherwise report it as empty. Absent is
// not unreadable: read('Makefile') where no Makefile exists is a question
// answered, so only a path the walk saw counts.
const unreadable = [];

const read = (p) => {
  try {
    return readFileSync(p, 'utf8');
  } catch {
    if (at.has(p)) unreadable.push(p);
    return null;
  }
};

// A manifest that will not parse is itself worth knowing, and silence about it
// reads as "there was nothing declared" — the one wrong thing a probe can say.
// Every parse() runs before the Commands section's unparsed check; Surprises reports
// unparsed unconditionally as a backstop. `read` also closes over `at` (defined after
// the walk below), so no `read` or `parse` call may precede `const at` — the first is
// `parse('package.json')`.
const unparsed = [];

const parse = (p) => {
  const text = read(p);
  if (!text) return null;
  try {
    return JSON.parse(text);
  } catch {
    // Named in the brief rather than thrown, so one bad file does not take the
    // rest of the run with it.
    unparsed.push(p);
    return null;
  }
};

// Whole-file reads across a repo to find a header is most of the run's cost for
// none of its value — the marker lives in the first few lines or nowhere.
function head(p, bytes = 2048) {
  let fd;
  try {
    fd = openSync(p, 'r');
    const buf = Buffer.alloc(bytes);
    const n = readSync(fd, buf, 0, bytes, 0);
    return buf.subarray(0, n).toString('utf8');
  } catch {
    return '';
  } finally {
    if (fd !== undefined) closeSync(fd);
  }
}

// A repo with no git is a fact for the brief, not a crash — the shared helper
// throws so hunt.mjs can refuse to run, and this is where that difference lives.
// Any git failure reads as "no git": a corrupt repo or blocked permission is
// indistinguishable from a fresh one, and the brief silently omits commit subjects.
const gitOrNull = (...args) => {
  try {
    return git(...args);
  } catch {
    return null;
  }
};

