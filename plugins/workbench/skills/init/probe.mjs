const read = (p) => {
  try {
    return readFileSync(p, 'utf8');
  } catch {
    return null;
  }
};

// A manifest that will not parse is itself worth knowing, and silence about it
// reads as "there was nothing declared" — the one wrong thing a probe can say.
const unparsed = [];

const parse = (p) => {
  const text = read(p);
  if (!text) return null;
  try {
    return JSON.parse(text);
  } catch {
    // Named in the brief rather than thrown, so one bad file does not take the
    // rest of the run with it.
    unparsed.push(p);
    return null;
  }
};

// Whole-file reads across a repo to find a header is most of the run's cost for
// none of its value — the marker lives in the first few lines or nowhere.
function head(p, bytes = 512) {
  let fd;
  try {
    fd = openSync(p, 'r');
    const buf = Buffer.alloc(bytes);
    const n = readSync(fd, buf, 0, bytes, 0);
    return buf.subarray(0, n).toString('utf8');
  } catch {
    return '';
  } finally {
    if (fd !== undefined) closeSync(fd);
  }
}

const git = (...args) => {
  try {
    return execFileSync('git', ['-c', 'core.quotePath=false', ...args], {
      encoding: 'utf8',
      maxBuffer: 8 << 20,
      stdio: ['ignore', 'pipe', 'pipe'],
    }).trimEnd();
  } catch {
    return null;
  }
};

function walk(dir, out = []) {
  if (out.length >= FILE_LIMIT) return out;
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    console.error(`unreadable directory, not scanned: ${dir}`);
    return out;
  }
  for (const entry of entries) {
    if (entry.isDirectory()) {
      if (!SKIP_DIR.has(entry.name)) walk(join(dir, entry.name), out);
    } else {
      out.push(relative(process.cwd(), join(dir, entry.name)).split(sep).join('/'));
    }
    if (out.length >= FILE_LIMIT) break;
  }
  return out;
}

function* blocks(text, anchor) {
  // A CRLF checkout is the default on Windows. Left in place, the trailing \r
  // defeats every `$` below and the file reads as having no commands at all.
  const lines = text.split(/\r?\n/);
  for (let i = 0; i < lines.length; i += 1) {
    const m = anchor.exec(lines[i]);
    if (!m) continue;
    const indent = m[1].length;
    const body = [];
    for (let j = i + 1; j < lines.length; j += 1) {
      if (!lines[j].trim()) continue;
      if (lines[j].length - lines[j].trimStart().length <= indent) break;
      body.push(lines[j]);
    }
    yield [m, body];
  }
}

function runSteps(text) {
  const out = [];
  // The dash belongs to the indent. Measured before it, `- run: |` sets a depth
  // two columns short of the step's own keys and swallows `env:` as a command.
  for (const [m, body] of blocks(text, /^(\s*(?:-\s+)?)run:\s*(.*)$/)) {
    const inline = m[2].trim();
    if (inline && !/^[|>]/.test(inline)) out.push(inline);
    else out.push(...body.map((line) => line.trim()));
  }
  return out;
}

function scriptSteps(text) {
  const out = [];
  for (const [, body] of blocks(text, /^(\s*)(?:before_script|script|after_script):\s*$/)) {
    for (const line of body) {
      const item = /^\s*-\s+(.*)$/.exec(line);
      if (item) out.push(item[1].trim().replace(/^["']|["']$/g, ''));
    }
  }
  return out;
}

